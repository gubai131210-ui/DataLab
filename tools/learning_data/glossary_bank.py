from __future__ import annotations

import re

HANZI = re.compile(r"[\u4e00-\u9fff]")


def _hanzi_n(text: str) -> int:
    return len(HANZI.findall(text or ""))


def T(term: str, plain: str, remember: str) -> dict[str, str]:
    plain = (plain or "").rstrip("。") + "。"
    remember = (remember or "").rstrip("。") + "。"
    if _hanzi_n(plain) < 12:
        plain = plain.rstrip("。") + "，先对着本课例子读一遍。"
    if _hanzi_n(remember) < 12:
        remember = remember.rstrip("。") + "，不要写成过程合格。"
    return {
        "term": term,
        "plain": plain,
        "remember": remember,
    }


def G(*triples: tuple[str, str, str]) -> list[dict[str, str]]:
    return [T(*row) for row in triples]


