# Duplicate keys must not sneak back in. BY_ID keys == overlay stems.


def glossary_for(cid: str, overlay: dict | None = None) -> list[dict[str, str]]:
    items = BY_ID.get(cid)
    if not items:
        title = (overlay or {}).get("title") or cid
        raise KeyError(f"glossary_bank missing command_id={cid} title={title}")
    return [dict(item) for item in items]


def expected_ids() -> set[str]:
    return set(BY_ID)
